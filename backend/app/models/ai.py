"""AEROSYNC — Gemini AI Explanation & Decision-Support Pydantic Models (Phase 8)."""

from datetime import datetime
from typing import Literal, Optional
from uuid import UUID, uuid4
from pydantic import BaseModel, Field
from app.models.common import now_utc

PROMPT_VERSION = "aerosync-ai-analysis-v1"


class AIAnalyzeRequest(BaseModel):
    """Authoritative input contract requesting situation analysis on a deterministic optimization run."""
    optimization_run_id: str = Field(..., description="UUID or identifier of the stored optimization run")
    include_situation_summary: bool = True
    include_allocation_explanations: bool = True
    include_unresolved_analysis: bool = True


class AIExplanation(BaseModel):
    """Structured natural-language explanation generated by Gemini Flash or deterministic fallback."""
    headline: str
    situation_summary: str
    key_changes: list[str] = Field(default_factory=list)
    optimization_summary: str
    allocation_insights: list[str] = Field(default_factory=list)
    unresolved_analysis: list[str] = Field(default_factory=list)
    constraint_observations: list[str] = Field(default_factory=list)
    operator_attention: list[str] = Field(default_factory=list)
    confidence: Literal["high", "medium", "low"] = "high"


class AIExplanationResponse(BaseModel):
    """Structured API response contract for POST /api/ai/analyze and GET /api/ai/analysis/{id}."""
    optimization_run_id: str
    provider: str = "gemini"
    model: str
    generated_at: datetime = Field(default_factory=now_utc)
    source: str = "optimization_result"
    explanation: AIExplanation
    fallback_used: bool = False
    error_code: Optional[str] = None
    prompt_version: str = PROMPT_VERSION


class AIAnalysisRecord(BaseModel):
    """Persisted AI analysis record stored distinctly from the immutable optimization result."""
    id: UUID = Field(default_factory=uuid4)
    optimization_run_id: UUID
    provider: str = "gemini"
    model: str
    prompt_version: str = PROMPT_VERSION
    generated_at: datetime = Field(default_factory=now_utc)
    explanation: AIExplanation
    status: str = "completed"
    fallback_used: bool = False
    error_code: Optional[str] = None

    model_config = {"from_attributes": True}


# Backwards compatibility aliases for earlier stub endpoints
AiAnalysisRequest = AIAnalyzeRequest
AiAnalysisResponse = AIExplanationResponse
